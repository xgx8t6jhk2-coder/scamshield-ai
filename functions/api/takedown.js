import { analyzeUrl } from '../../public/engine/scamshield.js';
import { rdap, doh } from '../_lib/enrich.js';
import { json, preflight } from '../_lib/http.js';

export const onRequestOptions = preflight;

/**
 * GET /api/takedown?domain=example.top
 * Builds a ready-to-send evidence package for the registrar / host / TDRA:
 * registrar + abuse contact (RDAP), DNS, engine findings, community report counts, and a drafted abuse notice.
 */
export async function onRequestGet({ request, env }) {
  const domain = String(new URL(request.url).searchParams.get('domain') || '').toLowerCase().replace(/[^a-z0-9.\-]/g, '').slice(0, 120);
  if (!domain || !domain.includes('.')) return json({ error: 'domain required' }, 400);

  const [r, a, ns, mx] = await Promise.all([rdap(domain), doh(domain, 'A'), doh(domain, 'NS'), doh(domain, 'MX')]);
  const engine = analyzeUrl('https://' + domain);
  let community = null, hunt = null;
  if (env.DB) {
    community = await env.DB.prepare(`SELECT COUNT(*) AS reports, SUM(lost_money) AS victims, MIN(created_at) AS first_seen, MAX(created_at) AS last_seen,
        GROUP_CONCAT(DISTINCT channel) AS channels, GROUP_CONCAT(DISTINCT playbook) AS playbooks FROM ss_reports WHERE domain = ?1`).bind(domain).first();
    hunt = await env.DB.prepare('SELECT source, first_seen, detail FROM ss_hunts WHERE domain = ?1').bind(domain).first();
  }
  const brand = engine.impersonatedBrand;
  const generated = new Date().toISOString();
  const ref = 'SSAI-' + generated.slice(0, 10).replace(/-/g, '') + '-' + [...domain].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7).toString(36).toUpperCase().slice(0, 6);

  const findings = engine.signals.filter((s) => s.weight > 0).map((s) => `- ${s.en}`).join('\n');
  const notice = `Subject: Urgent abuse report – phishing domain ${domain} (${ref})

To the abuse team of ${r?.registrar || 'the registrar'},

The domain ${domain} is being used to defraud residents of the United Arab Emirates${brand ? ` by impersonating ${brand.en} (official site: ${brand.official})` : ''}.

Evidence:
${findings || '- See attached technical package.'}
${community?.reports ? `- ${community.reports} independent reports from UAE residents between ${community.first_seen} and ${community.last_seen} (channels: ${community.channels}).` : ''}
${hunt ? `- First detected by proactive monitoring (${hunt.source}) on ${hunt.first_seen}: ${hunt.detail}.` : ''}
- DNS A records: ${(a?.answers || []).join(', ') || 'none'}; nameservers: ${(ns?.answers || r?.nameservers || []).join(', ') || 'unknown'}.
${r?.registered ? `- Domain registered on ${r.registered.slice(0, 10)} (${r.ageDays} days ago).` : ''}

We request suspension of the domain and preservation of registrant and payment records for law-enforcement purposes.

Reference: ${ref}
Generated by ScamShield AI on ${generated}`;

  return json({
    ref, domain, generated,
    verdict: engine.verdict, score: engine.score, impersonates: brand,
    signals: engine.signals,
    registration: r, dns: { a: a?.answers || [], ns: ns?.answers || [], mx: mx?.answers || [], status: a?.status },
    community, hunt,
    sendTo: [r?.abuseEmail && { who: 'Registrar abuse desk', email: r.abuseEmail, phone: r.abusePhone }, { who: 'TDRA (UAE telecom regulator) — block at ISP level', note: 'via official law-enforcement channel' }, { who: 'Google Safe Browsing', url: 'https://safebrowsing.google.com/safebrowsing/report_phish/' }, { who: 'Microsoft SmartScreen', url: 'https://www.microsoft.com/en-us/wdsi/support/report-unsafe-site' }].filter(Boolean),
    notice,
  });
}
